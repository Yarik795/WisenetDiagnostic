def build_workbook() -> Workbook:
    wb = Workbook()
    ws = wb.active
    ws.title = "Аналитика"
    ws.append(list(ANALYTICS_HEADERS))
    for row in ANALYTICS_ROWS:
        ws.append(list(row))

    general = wb.create_sheet("Общая информация")
    general.append(list(GENERAL_HEADERS))
    for row in GENERAL_ROWS:
        general.append(list(row))

    tsv = wb.create_sheet("ТСВ")
    tsv.append(
        [
            *COMMON_HEAD,
            "Наличие ТСВ",
            "Год установки, капитального ремонта ТСВ",
            "Количество аналоговых видеокамер камер на объекте",
            "Количество IP видеокамер камер на объекте",
            "Количество видеорегистраторов на объекте",
            "Вендоры IP оборудования на объекте",
        ]
    )
    for passport, name, year, analog, ip, nvr, vendor in TSV_ROWS:
        tsv.append([*_vsp_row(passport, name), "ДА", year, analog, ip, nvr, vendor])

    skud = wb.create_sheet("СКУД")
    skud.append(
        [
            *COMMON_HEAD,
            "Наличие СКУД",
            "Год установки, капитального ремонта СКУД",
            "Производитель контроллера",
            'Производитель (в случае если выбрано "Иное")',
        ]
    )
    for passport, name, year, manufacturer in SKUD_ROWS:
        skud.append([*_vsp_row(passport, name), "ДА", year, manufacturer, ""])

    saz = wb.create_sheet("САЗ")
